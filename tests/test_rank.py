def test_a_chs_jpn_ass_outranks_a_jpn_srt():
    """⭐ RULED 2026-09-17: ".ass above all else. even if it has chinese"."""
    ass = candidate(u"[Zeta] Sousou no Frieren - 31 [WebRip][CHS, JPN].ass", size=20000, quality="literal")
    srt = candidate(u"[Alpha] Sousou no Frieren - 31v2 [WebRip][JPN].srt", size=90000, quality="range")
    assert (tokens.language_class(ass.name), tokens.language_class(srt.name)) == ("multi", "single-ja")
    loses_every_lower_key(ass, srt, seen={srt.group})
    assert order(rank.rank([srt, ass], seen_groups=frozenset([srt.group]))) == [ass.name, srt.name]


def test_within_ass_jpn_outranks_chs_jpn_for_the_same_episode_and_release(episode_three):
    """The capture's own pair: the dual-language file is ~2x the size AND its
    name sorts first -- only the language rule can put `[JPN]` ahead."""
    by_group = {}
    for c in episode_three:
        if c.group == u"Haruhana" and tokens.subtitle_format(c.name) == "ass":
            by_group[tokens.language_class(c.name)] = c
    jpn, chs = by_group["single-ja"], by_group["multi"]
    assert jpn.info.episode == chs.info.episode
    loses_every_lower_key(jpn, chs)
    assert order(rank.rank([chs, jpn])) == [jpn.name, chs.name]


@pytest.mark.parametrize("marker", [u"[whisperai]", u"[Generated by Whisper]"])
def test_an_ai_file_is_excluded_unless_allowed_even_as_ass(marker):
    ai = candidate(u"[Alpha] Sousou no Frieren - 31 [JPN] %s.ass" % marker, size=90000)
    plain = candidate(u"[Zeta] Sousou no Frieren - 31.srt", size=20000, quality="literal")
    assert tokens.is_ai(ai.name) and not tokens.is_ai(plain.name)
    kept = rank.rank([ai, plain])
    assert order(kept) == [plain.name]
    assert [(c.name, u"AI-generated" in why) for c, why in kept.excluded] == [(ai.name, True)]
    allowed = rank.rank([ai, plain], allow_ai=True)
    assert order(allowed) == [ai.name, plain.name] and allowed.excluded == []


