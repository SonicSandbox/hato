def test_the_order_never_depends_on_the_input_order(episode_three):
    forward = order(rank.rank(list(episode_three)))
    assert order(rank.rank(list(reversed(episode_three)))) == forward
    assert len(forward) == len({c.name for c in episode_three})
    # ⚠ the capture never ties on every key, so a true tie is built: only the name is left
    a = candidate(u"[Alpha] Show - 03 [JPN].ass", size=30000)
    b = candidate(u"[Beta] Show - 03 [JPN].ass", size=30000)
    assert order(rank.rank([b, a])) == order(rank.rank([a, b])) == [a.name, b.name]


