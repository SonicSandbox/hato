def test_every_candidate_carries_the_reason_for_its_place(episode_three):
    ranking = rank.rank(episode_three)
    for i, r in enumerate(ranking.ordered):
        above = [s for s in r.reasons if s.startswith(u"Above #%d:" % (i + 2))]
        below = [s for s in r.reasons if s.startswith(u"Below #%d:" % i)]
        assert len(above) == (1 if i + 1 < len(ranking.ordered) else 0), r.reasons
        assert len(below) == (1 if i else 0), r.reasons
    names = [tokens.subtitle_format(r.candidate.name) for r in ranking.ordered]
    boundary = names.index("srt")
    assert u".ass is tried before .srt" in ranking.ordered[boundary].reasons[0]


def test_explain_prints_every_candidate_with_its_key_and_reasons_and_every_exclusion(episode_three):
    ai = candidate(u"[WhisperAI] Sousou no Frieren - 31.ass")
    ranking = rank.rank(list(episode_three) + [ai])
    text = rank.explain(ranking)
    lines = text.splitlines()
    for i, r in enumerate(ranking.ordered):
        row = [l for l in lines if l.endswith(r.candidate.name) and l.split()[0] == str(i + 1)]
        assert len(row) == 1, r.candidate.name
        assert u"{:,}".format(r.candidate.file["size"]) in row[0]
        assert all(reason in text for reason in r.reasons)
    assert u"EXCLUDED" in text and ai.name in text.split(u"EXCLUDED", 1)[1]


