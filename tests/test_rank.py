def test_a_chs_jpn_ass_outranks_a_jpn_srt():
    """⭐ RULED 2026-09-17: ".ass above all else. even if it has chinese"."""
    ass = candidate(u"[Zeta] Sousou no Frieren - 31 [WebRip][CHS, JPN].ass", size=20000, quality="literal")
