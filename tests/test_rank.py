def test_size_is_never_compared_across_a_format_or_a_language_class(episode_three):
    """⚠ The rule, not a pair: turn every size upside down and no candidate may
    cross a format or a language-class boundary -- only order inside one moves."""
    def buckets(cands):
        return [(tokens.subtitle_format(r.candidate.name), tokens.language_class(r.candidate.name))
                for r in rank.rank(cands).ordered]

    sizes = [c.file["size"] for c in episode_three]
    flipped = []
    for c in episode_three:
        f = dict(c.file, size=max(sizes) + min(sizes) - c.file["size"])
        flipped.append(episodes.Candidate(f, c.info, c.group, c.offset, c.quality, c.coverage, c.reason))
    before, after = buckets(episode_three), buckets(flipped)
    assert len(set(before)) > 2, before
    assert after == before
    assert order(rank.rank(flipped)) != order(rank.rank(episode_three)), "size still orders inside a bucket"


def test_two_formats_outside_the_ruled_order_are_never_separated_by_size():
    """🚨 SIZE *WAS* COMPARED ACROSS FORMATS. `.ass`, `.ssa` and `.srt` are
    ranked; everything else shared ONE rank -- so a `.vtt` and a `.sup` tied on
    part 1, fell through to part 7 and were ordered by SIZE, while the printed
    reason said *"size is only ever compared between .vtt Japanese-only files"*.
    The invariant of key part 7 was simply false.

    ⚠ THE CAPTURE HOLDS ONLY `.ass` AND `.srt`, so the rule-shaped check above
    -- which flips every size on the real capture -- structurally cannot see it.
    The format is what varies here.
    """
    big = candidate(u"[Alpha] Show - 03 [JPN].sup", size=90000)
    small = candidate(u"[Zeta] Show - 03 [JPN].vtt", size=10000)
    assert {tokens.subtitle_format(c.name) for c in (big, small)} == {"sup", "vtt"}
    assert not {tokens.subtitle_format(c.name) for c in (big, small)} & set(rank.FORMAT_ORDER)
    # the rescue trap: the loser wins every key below the one under test
    assert big.file["size"] > small.file["size"] and big.name < small.name

    ranking = rank.rank([small, big])
    assert order(ranking) == [big.name, small.name]         # .sup < .vtt, by extension
    why = u" ".join(ranking.ordered[0].reasons)
    assert u"the extension decides" in why and u"Never their size" in why, why
    # and the sizes are what would have decided it the other way
    flipped = candidate(u"[Alpha] Show - 03 [JPN].sup", size=10000)
    assert order(rank.rank([small, flipped])) == [flipped.name, small.name]


def test_an_unbroken_tie_guess_is_tried_after_a_literal_number():
    """⭐ `guess` sits BELOW `literal`. An anchored placement is a coin flip
    between the members of a tie; a literal number is what both sides wrote
    down. Ranked as an `overlap` -- which is what it used to be -- a
    wrong-episode guess took #1 from a correctly-placed release."""
    guess = candidate(u"[Alpha] Show - 03 [JPN].ass", size=90000, quality="guess", coverage=1.0)
    literal = candidate(u"[Zeta] Show - 03 [JPN].ass", size=10000, quality="literal", coverage=0.1)
    assert episodes.QUALITIES.index("guess") > episodes.QUALITIES.index("literal")
    assert guess.file["size"] > literal.file["size"] and guess.name < literal.name
    ranking = rank.rank([guess, literal])
    assert order(ranking) == [literal.name, guess.name]
    # ⚠ AMENDED 2026-09-17: the sentence moved UP a key part and got stronger. A
    # guess used to lose to a literal number on `fit`, which sits BELOW format --
    # so an `.ass` guess still beat an `.srt` literal number (measured live, and it
    # took #1 from files whose own number read 3). Now it loses on `known`, which
    # sits above format. ⭐ The behaviour asserted above is unchanged; what changed
    # is that it now holds whatever format either file is in.
    said = u" ".join(ranking.ordered[0].reasons)
    assert u"known, not guessed" in said and u"whatever format" in said, said


def test_the_offset_both_sides_already_name_breaks_a_tie_between_equal_fits():
    """⭐ A NEW KEY PART, and nothing used this evidence. Two candidates that
    tie on format, language, fit and coverage used to fall straight to size and
    the name -- so a release re-numbered by +28 could take #1 from one whose
    file and video agree on the episode. The agreeing one goes first."""
    agreed = candidate(u"[Zeta] Show - 03 [JPN].ass", size=10000)
    shifted = candidate(u"[Alpha] Show - 03 [JPN].ass", size=90000)
    shifted = episodes.Candidate(shifted.file, None, shifted.group, 28, "range", 1.0, u"shifted")
    assert agreed.offset == 0 and shifted.offset == 28
    assert agreed.quality == shifted.quality and agreed.coverage == shifted.coverage
    # the rescue trap: the winner loses size AND the name
    assert agreed.file["size"] < shifted.file["size"] and agreed.name > shifted.name
    ranking = rank.rank([shifted, agreed])
    assert order(ranking) == [agreed.name, shifted.name]
    assert u"both sides already name" in u" ".join(ranking.ordered[0].reasons)


