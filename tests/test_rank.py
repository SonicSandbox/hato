def test_ssa_goes_before_srt_and_srt_before_the_rest():
    ssa = candidate(u"[Zeta] Show - 03 [JPN].ssa", size=10000, quality="literal")
    srt = candidate(u"[Mid] Show - 03 [JPN].srt", size=20000, quality="overlap")
    rest = candidate(u"[Alpha] Show - 03 [JPN].vtt", size=90000)
    loses_every_lower_key(ssa, srt)
    loses_every_lower_key(srt, rest)
    assert order(rank.rank([rest, srt, ssa])) == [ssa.name, srt.name, rest.name]


