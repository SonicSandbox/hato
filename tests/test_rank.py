def candidate(name, size=30000, quality="range", coverage=1.0, group=None):
    f = {"name": name, "size": size, "last_modified": FILES[0]["last_modified"],
         "url": FILES[0]["url"].rsplit("/", 1)[0] + "/constructed"}
    return episodes.Candidate(f, None, group or tokens.release_group(name), 0, quality, coverage,
                              u"constructed for a ranking check")


def order(ranking):
    return [r.candidate.name for r in ranking.ordered]


def loses_every_lower_key(winner, loser, seen=frozenset()):
    """The arrangement the rescue trap needs, asserted rather than assumed."""
    assert winner.file["size"] < loser.file["size"]
    assert tokens.version(winner.name) <= tokens.version(loser.name)
    assert episodes.QUALITIES.index(winner.quality) >= episodes.QUALITIES.index(loser.quality)
    assert winner.group not in seen
    assert winner.name > loser.name


